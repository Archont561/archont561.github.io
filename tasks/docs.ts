import { readFileSync } from "node:fs";
import { join } from "node:path";
import { task, tasks, updateTextFile } from "@archont561/tools/tasks";

/** Frontmatter takes priority; older backlog documents use a bold status line. */
export function statusOf(text: string): string {
  const frontmatter = text.match(/^---\s*\n([\s\S]*?)\n---(?:\n|$)/)?.[1];
  const front = frontmatter?.match(/^status\s*:\s*["']?([^\n"']+)["']?\s*$/im)?.[1];
  const line = text.match(/^(?:\*\*)?status:(?:\*\*)?\s*([^\n·]+)/im)?.[1];
  return (front ?? line ?? "unknown").replaceAll("**", "").trim();
}

export function renderBacklogIndex(root: string): string {
  const sections = ["milestones", "tasks", "decisions", "docs"];
  const lines = [
    "# Backlog index",
    "",
    "Generated by `pixi run tools task docs:index`. Edit the source documents, not this index.",
    "",
  ];
  for (const section of sections) {
    lines.push(
      `## ${section[0]?.toUpperCase()}${section.slice(1)}`,
      "",
      "| Document | Status |",
      "| --- | --- |",
    );
    const files = [
      ...new Bun.Glob(`${section}/*.md`).scanSync({ cwd: join(root, "backlog"), onlyFiles: true }),
    ]
      .filter((file) => !file.endsWith("/README.md"))
      .sort();
    for (const file of files) {
      const text = readFileSync(join(root, "backlog", file), "utf8");
      const title = text.match(/^#\s+(.+)$/m)?.[1] ?? file.split("/").at(-1) ?? file;
      lines.push(
        `| [${title.replaceAll("|", "\\|")}](${file}) | ${statusOf(text).replaceAll("|", "\\|")} |`,
      );
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

export default tasks(
  task({
    name: "docs:index",
    fileDep: ["backlog/**/*.md", "tasks/docs.ts"],
    targets: ["backlog/README.md"],
    run: ({ root }) => {
      updateTextFile(join(root, "backlog/README.md"), renderBacklogIndex(root), false);
    },
  }),
  task({
    name: "docs:index:check",
    fileDep: ["backlog/**/*.md", "tasks/docs.ts"],
    run: ({ root }) => {
      if (updateTextFile(join(root, "backlog/README.md"), renderBacklogIndex(root), true)) {
        throw new Error("backlog/README.md is out of date; run pixi run tools task docs:index");
      }
    },
  }),
);
